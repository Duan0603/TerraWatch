package vn.terrawatch.core.service;

import org.junit.jupiter.api.Test;
import org.springframework.web.server.ResponseStatusException;
import vn.terrawatch.core.dto.SubscriptionRequest;
import vn.terrawatch.core.dto.SubscriptionResponse;
import vn.terrawatch.core.entity.AlertSubscription;
import vn.terrawatch.core.entity.MonitoringArea;
import vn.terrawatch.core.entity.User;
import vn.terrawatch.core.repository.AlertSubscriptionRepository;
import vn.terrawatch.core.repository.MonitoringAreaJpaRepository;
import vn.terrawatch.core.repository.UserRepository;

import java.util.List;
import java.util.Optional;
import java.util.UUID;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.Mockito.mock;
import static org.mockito.Mockito.never;
import static org.mockito.Mockito.verify;
import static org.mockito.Mockito.verifyNoInteractions;
import static org.mockito.Mockito.when;

/** Complements ProfileAndSubscriptionServiceTest, which already covers subscribe happy path, SMS-needs-phone, inactive/unknown area and foreign unsubscribe. */
class AlertSubscriptionServiceTest {
    private final AlertSubscriptionRepository subs = mock(AlertSubscriptionRepository.class);
    private final MonitoringAreaJpaRepository areas = mock(MonitoringAreaJpaRepository.class);
    private final UserRepository users = mock(UserRepository.class);
    private final AlertSubscriptionService service = new AlertSubscriptionService(subs, areas, users);
    private final UUID me = UUID.randomUUID();

    /** The id is generated by the database, so give every in-memory row one. */
    private static AlertSubscription sub(UUID user, int area, boolean push, boolean sms) {
        AlertSubscription s = new AlertSubscription(user, area, push, sms);
        try {
            var f = AlertSubscription.class.getDeclaredField("subscriptionId");
            f.setAccessible(true);
            f.set(s, UUID.randomUUID());
        } catch (ReflectiveOperationException e) {
            throw new IllegalStateException(e);
        }
        return s;
    }

    private MonitoringArea area(int id, String name) {
        MonitoringArea a = new MonitoringArea(name, "d", true);
        a.setAreaId(id);
        when(areas.findById(id)).thenReturn(Optional.of(a));
        return a;
    }

    private User user(String phone) {
        User u = new User("An", "an@x.vn", "h", "citizen", phone);
        u.setUserId(me);
        when(users.findById(me)).thenReturn(Optional.of(u));
        return u;
    }

    private static void assertStatus(Runnable action, int status) {
        assertThatThrownBy(action::run).isInstanceOfSatisfying(ResponseStatusException.class,
            e -> assertThat(e.getStatusCode().value()).isEqualTo(status));
    }

    @Test
    void listKeepsRepositoryOrderResolvesAreaNamesAndHandlesAMissingArea() {
        AlertSubscription first = sub(me, 2, true, false);
        AlertSubscription second = sub(me, 1, false, true);
        AlertSubscription orphan = sub(me, 9, true, true);
        when(subs.findByUserIdAndActiveTrueOrderBySubscribedAtDesc(me)).thenReturn(List.of(first, second, orphan));
        when(areas.findAllById(List.of(2, 1, 9))).thenReturn(List.of(
            new MonitoringArea("Sa Pa", "d", true) {{ setAreaId(2); }},
            new MonitoringArea("Mu Cang Chai", "d", true) {{ setAreaId(1); }}));

        List<SubscriptionResponse> out = service.list(me);

        assertThat(out).extracting(SubscriptionResponse::areaId).containsExactly(2, 1, 9);
        assertThat(out).extracting(SubscriptionResponse::areaName).containsExactly("Sa Pa", "Mu Cang Chai", null);
        assertThat(out.get(0).alertChannels()).containsExactly("PUSH");
        assertThat(out.get(1).alertChannels()).containsExactly("SMS");
        assertThat(out.get(2).alertChannels()).containsExactly("PUSH", "SMS");
    }

    @Test
    void listForUserWithoutSubscriptionsIsEmpty() {
        when(subs.findByUserIdAndActiveTrueOrderBySubscribedAtDesc(me)).thenReturn(List.of());
        when(areas.findAllById(List.of())).thenReturn(List.of());
        assertThat(service.list(me)).isEmpty();
    }

    @Test
    void pushOnlySubscriptionNeverLooksUpOrChangesTheUsersPhone() {
        area(1, "Sa Pa");
        when(subs.findByUserIdAndAreaId(me, 1)).thenReturn(Optional.empty());
        when(subs.save(any(AlertSubscription.class))).thenAnswer(c -> {
            AlertSubscription s = c.getArgument(0);
            return s.getSubscriptionId() == null ? sub(me, s.getAreaId(), s.isChannelPush(), s.isChannelSms()) : s;
        });

        SubscriptionResponse out = service.subscribe(me, new SubscriptionRequest(1, List.of("PUSH"), "0912345678"));

        assertThat(out.alertChannels()).containsExactly("PUSH");
        verifyNoInteractions(users);
    }

    @Test
    void smsUsesThePhoneAlreadyOnTheProfileAndLeavesItUnchanged() {
        area(1, "Sa Pa");
        User u = user("0901111111");
        when(subs.findByUserIdAndAreaId(me, 1)).thenReturn(Optional.empty());
        when(subs.save(any(AlertSubscription.class))).thenAnswer(c -> {
            AlertSubscription s = c.getArgument(0);
            return s.getSubscriptionId() == null ? sub(me, s.getAreaId(), s.isChannelPush(), s.isChannelSms()) : s;
        });

        for (String requestPhone : new String[]{null, "", "  "}) {
            assertThat(service.subscribe(me, new SubscriptionRequest(1, List.of("SMS"), requestPhone)).alertChannels()).containsExactly("SMS");
        }
        assertThat(u.getPhoneNumber()).isEqualTo("0901111111");
        verify(users, never()).save(any());
    }

    @Test
    void phoneInTheRequestReplacesTheProfilePhone() {
        area(1, "Sa Pa");
        User u = user("0901111111");
        when(subs.findByUserIdAndAreaId(me, 1)).thenReturn(Optional.empty());
        when(subs.save(any(AlertSubscription.class))).thenAnswer(c -> {
            AlertSubscription s = c.getArgument(0);
            return s.getSubscriptionId() == null ? sub(me, s.getAreaId(), s.isChannelPush(), s.isChannelSms()) : s;
        });
        when(users.save(any(User.class))).thenAnswer(c -> c.getArgument(0));

        service.subscribe(me, new SubscriptionRequest(1, List.of("SMS"), "0922222222"));

        assertThat(u.getPhoneNumber()).isEqualTo("0922222222");
        verify(users).save(u);
    }

    @Test
    void smsWithNoPhoneAnywhereIs400AndSavesNothing() {
        area(1, "Sa Pa");
        user("  ");
        assertStatus(() -> service.subscribe(me, new SubscriptionRequest(1, List.of("SMS"), null)), 400);
        verify(subs, never()).save(any());
    }

    @Test
    void smsForUnknownUserIs401() {
        area(1, "Sa Pa");
        when(users.findById(me)).thenReturn(Optional.empty());
        assertStatus(() -> service.subscribe(me, new SubscriptionRequest(1, List.of("SMS"), "0912345678")), 401);
    }

    @Test
    void resubscribingAnExistingAreaOverwritesChannelsOnTheSameRow() {
        area(1, "Sa Pa");
        AlertSubscription existing = sub(me, 1, true, true);
        when(subs.findByUserIdAndAreaId(me, 1)).thenReturn(Optional.of(existing));
        when(subs.save(any(AlertSubscription.class))).thenAnswer(c -> {
            AlertSubscription s = c.getArgument(0);
            return s.getSubscriptionId() == null ? sub(me, s.getAreaId(), s.isChannelPush(), s.isChannelSms()) : s;
        });

        service.subscribe(me, new SubscriptionRequest(1, List.of("PUSH"), null));

        assertThat(existing.isChannelPush()).isTrue();
        assertThat(existing.isChannelSms()).isFalse();
        verify(subs).save(existing);
    }

    @Test
    void ownerUnsubscribeDeletesTheRow() {
        UUID id = UUID.randomUUID();
        AlertSubscription mine = sub(me, 1, true, true);
        when(subs.findBySubscriptionIdAndUserId(id, me)).thenReturn(Optional.of(mine));
        service.unsubscribe(me, id);
        verify(subs).delete(mine);
    }
}
