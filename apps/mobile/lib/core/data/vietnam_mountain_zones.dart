      return null;
    }
  }

  static List<MountainZone> getZonesByProvince(String province) {
    return zones.where((z) => z.provinceVi == province).toList();
  }

  static List<MountainZone> getCriticalZones() {
    return zones.where((z) => z.tier == SusceptibilityTier.CRITICAL).toList();
  }

  static List<String> getAvailableProvinces() {
    return zones.map((z) => z.provinceVi).toSet().toList()..sort();
