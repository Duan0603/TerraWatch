class CoordinatePoint {
  final double longitude;
  final double latitude;

  const CoordinatePoint(this.longitude, this.latitude);

  Map<String, dynamic> toJson() => {
    'lng': longitude,
    'lat': latitude,
  };
}

enum SusceptibilityTier {
  CRITICAL,
  HIGH,
  MODERATE,
  LOW,
}

class TopographyProfile {
  final double meanElevationM;
  final double peakElevationM;
  final double meanSlopeDegrees;
  final double maxSlopeDegrees;
  final String dominantAspect;

  const TopographyProfile({
    required this.meanElevationM,
    required this.peakElevationM,
    required this.meanSlopeDegrees,
    required this.maxSlopeDegrees,
    required this.dominantAspect,
  });
}

class HydrologyProfile {
  final double flowAccumulationMean;
  final double topographicWetnessIndex;
  final double annualRainfallMm;
  final double criticalRainfall24hMm;
  final double criticalRainfall72hMm;

  const HydrologyProfile({
    required this.flowAccumulationMean,
    required this.topographicWetnessIndex,
    required this.annualRainfallMm,
    required this.criticalRainfall24hMm,
    required this.criticalRainfall72hMm,
  });
}

class MountainZone {
  final String zoneId;
  final String nameVi;
  final String nameEn;
  final String provinceVi;
  final String provinceEn;
  final SusceptibilityTier tier;
  final CoordinatePoint center;
  final TopographyProfile topography;
  final HydrologyProfile hydrology;
  final int historicalEventsCount;
  final String stationCode;

  const MountainZone({
    required this.zoneId,
    required this.nameVi,
    required this.nameEn,
    required this.provinceVi,
    required this.provinceEn,
    required this.tier,
    required this.center,
    required this.topography,
    required this.hydrology,
    required this.historicalEventsCount,
    required this.stationCode,
  });
}

